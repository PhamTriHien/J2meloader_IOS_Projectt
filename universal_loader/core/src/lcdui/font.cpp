// Caching up to 72 fonts (3 faces * 3 sizes * 8 styles)
static std::array<std::shared_ptr<LcduiFont>, 72> s_fontCache;
static std::mutex s_fontMutex;

LcduiFont::LcduiFont(int face, int style, int size, float customHeight)
    : m_face(face), m_style(style), m_size(size) {
    
    // Scale and metrics aligned with upstream J2ME-Loader
    if (customHeight > 0.0f) {
        m_height = static_cast<int>(std::ceil(customHeight));
    } else {
        if (size == SIZE_SMALL) {
            m_height = 13;
        } else if (size == SIZE_LARGE) {
            m_height = 24;
        } else {
            m_height = 18; // SIZE_MEDIUM default
        }
    }

    if (m_height <= 14) {
        m_scale = 1;
        m_ascent = 10;
        m_descent = m_height - m_ascent;
    } else if (m_height <= 20) {
        m_scale = 2; // Scaled or styled
        m_ascent = 14;
        m_descent = m_height - m_ascent;
    } else {
        m_scale = 2;
        m_ascent = 19;
        m_descent = m_height - m_ascent;
    }
}

std::shared_ptr<LcduiFont> LcduiFont::getFont(int face, int style, int size) {
    int faceIdx = 0;
    if (face == FACE_MONOSPACE) faceIdx = 1;
    else if (face == FACE_PROPORTIONAL) faceIdx = 2;

    int sizeIdx = 0;
    if (size == SIZE_SMALL) sizeIdx = 1;
    else if (size == SIZE_LARGE) sizeIdx = 2;

    int styleIdx = style & 7;
    int cacheIdx = (faceIdx * 3 + sizeIdx) * 8 + styleIdx;
    if (cacheIdx < 0 || cacheIdx >= 72) cacheIdx = 0;

    std::lock_guard<std::mutex> lock(s_fontMutex);
    if (!s_fontCache[cacheIdx]) {
        s_fontCache[cacheIdx] = std::make_shared<LcduiFont>(face, style, size);
    }
    return s_fontCache[cacheIdx];
}

std::shared_ptr<LcduiFont> LcduiFont::getDefaultFont() {
    return getFont(FACE_SYSTEM, STYLE_PLAIN, SIZE_MEDIUM);
}

std::shared_ptr<LcduiFont> LcduiFont::getFont(int fontSpecifier) {
    (void)fontSpecifier;
    return getDefaultFont();
}

int LcduiFont::getCharBaseWidth(char c) const {
    if (m_face == FACE_MONOSPACE) {
        return 8;
    }

    // Proportional character width estimation
    if (c == ' ' || c == '.' || c == ',' || c == ':' || c == ';' || c == '!' || c == '|' || c == '\'') {
        return 4;
    }
    if (c == 'i' || c == 'l' || c == '`' || c == '(' || c == ')' || c == '[' || c == ']' || c == '{' || c == '}') {
        return 5;
    }
    if (c == 'f' || c == 't' || c == 'r' || c == 'j') {
        return 6;
    }
    if (c == 'm' || c == 'w' || c == 'M' || c == 'W' || c == '@' || c == '%' || c == '#') {
        return 9;
    }
    return 7;
}

int LcduiFont::charWidth(char c) const {
    if (c < 32 || c > 126) return 0;
    int baseW = getCharBaseWidth(c);
    int boldAdd = isBold() ? 1 : 0;
    if (m_scale == 2) {
        return (baseW + boldAdd) * 2;
    }
    return baseW + boldAdd;
}

int LcduiFont::charsWidth(const char* ch, int offset, int length) const {
    if (!ch || offset < 0 || length <= 0) return 0;
    int total = 0;
    for (int i = 0; i < length; ++i) {
        total += charWidth(ch[offset + i]);
    }
    return total;
}

int LcduiFont::stringWidth(const std::string& text) const {
    return charsWidth(text.data(), 0, static_cast<int>(text.size()));
}

int LcduiFont::substringWidth(const std::string& str, int offset, int len) const {
    if (offset < 0 || len <= 0 || offset >= static_cast<int>(str.size())) return 0;
    int actualLen = std::min(len, static_cast<int>(str.size()) - offset);
    return charsWidth(str.data(), offset, actualLen);
}

void LcduiFont::renderChar(char c, uint32_t* target, int bufW, int bufH,
                           int clipX, int clipY, int clipW, int clipH,
                           int x, int y, uint32_t color) const {
    if (!target || c < 32 || c > 126) return;
    const uint8_t* glyph = GLYPH_DATA[c - 32];

    int scale = m_scale;
    bool bold = isBold();
    bool italic = isItalic();

    uint8_t a = (color >> 24) & 0xFF;
    if (a == 0) a = 0xFF; // Non-zero alpha default

    for (int row = 0; row < 8; ++row) {
        uint8_t rowBits = glyph[row];
        int italicShift = italic ? ((7 - row) / 3) * scale : 0;

        for (int col = 0; col < 8; ++col) {
            if ((rowBits & (0x80 >> col)) != 0) {
                for (int sy = 0; sy < scale; ++sy) {
                    int py = y + row * scale + sy;
                    if (py < clipY || py >= clipY + clipH || py < 0 || py >= bufH) continue;

                    for (int sx = 0; sx < scale; ++sx) {
                        int px = x + italicShift + col * scale + sx;
                        if (px >= clipX && px < clipX + clipW && px >= 0 && px < bufW) {
                            target[py * bufW + px] = color;
                        }
                        if (bold) {
                            int bpx = px + 1;
                            if (bpx >= clipX && bpx < clipX + clipW && bpx >= 0 && bpx < bufW) {
                                target[py * bufW + bpx] = color;
                            }
                        }
                    }
                }
            }
        }
    }

    if (isUnderlined()) {
        int charW = charWidth(c);
        int lineY = y + m_ascent + 1;
        if (lineY >= clipY && lineY < clipY + clipH && lineY >= 0 && lineY < bufH) {
            for (int dx = 0; dx < charW; ++dx) {
                int px = x + dx;
                if (px >= clipX && px < clipX + clipW && px >= 0 && px < bufW) {
                    target[lineY * bufW + px] = color;
                }
            }
        }
    }
}

void LcduiFont::renderString(const std::string& text, uint32_t* target, int bufW, int bufH,
                            int clipX, int clipY, int clipW, int clipH,
                            int x, int y, int anchor, uint32_t color) const {
    renderSubstring(text, 0, static_cast<int>(text.size()), target, bufW, bufH, clipX, clipY, clipW, clipH, x, y, anchor, color);
}

void LcduiFont::renderSubstring(const std::string& text, int offset, int len,
                                uint32_t* target, int bufW, int bufH,
                                int clipX, int clipY, int clipW, int clipH,
                                int x, int y, int anchor, uint32_t color) const {
    if (!target || offset < 0 || len <= 0 || offset >= static_cast<int>(text.size())) return;
    int actualLen = std::min(len, static_cast<int>(text.size()) - offset);

    int totalW = charsWidth(text.data(), offset, actualLen);
    int totalH = m_height;

    // Anchor calculation matching MIDP 2.0 Graphics specification
    int lx = x;
    if (anchor & ANCHOR_RIGHT) {
        lx = x - totalW;
    } else if (anchor & ANCHOR_HCENTER) {
        lx = x - (totalW / 2);
    }

    int ly = y;
    if (anchor & ANCHOR_BOTTOM) {
        ly = y - totalH;
    } else if (anchor & ANCHOR_VCENTER) {
        ly = y - (totalH / 2);
    } else if (anchor & ANCHOR_BASELINE) {
        ly = y - m_ascent;
    }

    int curX = lx;
    for (int i = 0; i < actualLen; ++i) {
        char c = text[offset + i];
        renderChar(c, target, bufW, bufH, clipX, clipY, clipW, clipH, curX, ly, color);
        curX += charWidth(c);
    }
}

